/**
 * paradigma adalah polapikir, kerangka, cara pandang
 * paradigma oop = didasari  pada konsep objek yang memiliki
 * atribut serta dapat melakukan suatu tindakan (method)
 * 
 * 4 pilar oop
 * -encapsulation (pembungkusan)
 * -inheritance (pewarisan)
 * -polymorphism (keluwesan)
 * -abstraction (pengabstrakan)
 * 
 * .encapsulation
 * => ibarat sebuah kantong yang menyimpan sesuatu dalam pemograman
 * berfungsi
 * mengumpulkan data dan tidak dapat diakses langsung dari luar
 * pada kasus 'ucup guerrero' kita tidak bisa mengubah
 * berat badan dari ucup tapi kita bisa menambahkannya melalui
 * fungsi / method makan ()
 * 
 * .abstraction
 * => bisa dibilang penerapan alami dari encapsulation
 * yang mana abstraction berarti sebuah objek yang hanya
 * menunjukkan operasinya secara high-level
 * misalnya kita hanya cukup tau bagaimana ucup makan
 * namun kita tidak perlu tau bagaimana sistem metabolisme biologis dalam tubuh si ucup
 * yang membuat berat badannya bertambah
 * 
 * .inheritance
 * => Beberapa objek bisa memiliki beberapa karakteristik yang sama
 * maka dari itu kita tidak perlu menulis ulang
 * kode yang sama berkali-kali
 * namun mereka bukanlah objek yang sama
 * inheritance pada ucup guerrero memiliki sifat dan perilaku yang umum
 * dengan manusia lain. seperti berat, warna, tinggi badan dsb.
 * maka ucup guerreri sebagai obbjek turunan atau (Subclass).
 * induk classnya disebut > (Superclass) atau (Parent Class).
 * 
 * .polymorphism
 * ** banyak bentuk **
 * objek dapat memiliki bentuk atau implementasi yang berbeda-beda
 * pada satu metode yang sama
 * manusia bergerak, akan tetapi cara gerak ucup guerero dengan cara gerak kenzie ahnaf berbeda
 * itulah yang merupakan contoh dari polymorphism
 * 
 * 
 * 
 */